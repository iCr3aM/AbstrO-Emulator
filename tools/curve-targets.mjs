/**
 * 目标时长向量 —— 唯一真相源（GDD §2：一局 5.20 小时 / 八章）
 * ===============================================================
 * 为什么单独一个文件：标定器（recalibrate-curve.mjs）与量尺（headless-check.mjs）
 * 必须读**同一份**「目标」。各写一份就会出现「标定到 5.2h、验收按 40–60h」这种漂移，
 * 而本计划存在的全部意义，就是把「一章多长」收敛到一个地方。
 *
 * 单位一律是**真实小时**：它不随 LINE_COST0 变，是标定器去追的东西。
 */

/** 目标合计时长（小时）：GDD §2 八段之和。 */
export const TARGET_TOTAL_H = 5.2;

/** 主动玩法（每年做最优决策）的验收带宽（小时）—— headless-check 用它判 ❌/✅。 */
export const CURVE_BAND = [3, 6];

/**
 * 纯挂机玩法（待决事件全按默认选项结算）的验收带宽（小时）。
 * 上限放宽到目标的 3.75 倍：默认选项一律是**保守项**（保住现金、不换乘数），
 * 所以挂机必然比主动慢 —— 要求两条路径落在同一区间等于要求「不决策不会变慢」，
 * 自相矛盾。这里守的是「挂机也一定能通关，且不会慢到荒谬」。
 */
export const IDLE_BAND = [3, 18];

/**
 * 每章目标时长（小时；第 0 项占位）。**非递减**，合计 = TARGET_TOTAL_H。
 *
 * 形状的理由（八章）：一章的购买次数 ∝ 它的 `ln(市值)` 台阶，而真实营收阶梯的
 * `ln` 比率是**递减**的（同一款产品从 1 到 10 倍容易，从 100 亿到 1000 亿难得多）。
 * v6 起末章**目标拉到 1.10h**（占全程 21%）：用户要求「终局是最刺激的阶段，不应该加快」。
 * ⚠️ 但第四批实测末章 `1.068h ≲ 第 7 章 1.114h` —— 单章容差 ±`40%` 允许这种反超
 * （第 7 章实测贴着容差上界 `dev 0.393`），且 §4.1 #6 已裁定「末章不必须最长」。
 */
export const CURVE_MID = [null, 0.36, 0.46, 0.54, 0.60, 0.64, 0.70, 0.80, 1.10];

/** 单章验收容差：|实测 / 目标 − 1| ≤ CURVE_TOL 视为达标（标定器也用它判收敛）。 */
export const CURVE_TOL = 0.4;

/** 全程叙事跨度（游戏年，2026–2066）—— 由 `ACTS[].years` 派生，这里只作对照。 */
export const NARRATIVE_YEARS = 40;

// ── 自洽守卫：合计必须等于 TARGET_TOTAL_H，非递减，否则这张表自己就是错的 ──
const sum = CURVE_MID.slice(1).reduce((a, b) => a + b, 0);
if (Math.abs(sum - TARGET_TOTAL_H) > 1e-9) {
  throw new Error(`CURVE_MID 合计 ${sum}h ≠ TARGET_TOTAL_H ${TARGET_TOTAL_H}h —— 两者必须同步修改`);
}
for (let a = 2; a <= 8; a++) {
  if (!(CURVE_MID[a] >= CURVE_MID[a - 1])) {
    throw new Error(`CURVE_MID 必须非递减：第 ${a} 章 ${CURVE_MID[a]}h < 第 ${a - 1} 章 ${CURVE_MID[a - 1]}h`);
  }
}
