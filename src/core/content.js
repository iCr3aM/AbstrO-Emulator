export const VAL_CYCLE_AMP = 0.25;
export const CYCLE_MONTHS = 120;
/** 骤跌 / 急涨那一段的长度（月）。调大 = 跌得更平缓，调小 = 崩得更陡。 */
export const CYCLE_CRASH = 3;
/** 缓涨 / 缓跌那一段的长度 = (120 − 2×3) / 2 = 57 */
export const CYCLE_RISE = (CYCLE_MONTHS - CYCLE_CRASH * 2) / 2;

/**
 * 「市场温度」：`+1` = 最热（估值最高、成本最低）｜ `−1` = 最冷（估值最低、成本最贵）
 * ｜ `0` = 平常。锯齿、周期 120 月、均值 0、过零点在月 0 与 120。
 */
export const cycleAt = m => {
  const u = ((m % CYCLE_MONTHS) + CYCLE_MONTHS) % CYCLE_MONTHS;
  if (u < CYCLE_RISE) return u / CYCLE_RISE;                                   // 缓涨 0 → +1
  if (u < CYCLE_RISE + CYCLE_CRASH) return 1 - (u - CYCLE_RISE) / CYCLE_CRASH; // 骤跌 +1 → 0
  if (u < CYCLE_MONTHS - CYCLE_CRASH) return -(u - CYCLE_RISE - CYCLE_CRASH) / CYCLE_RISE; // 缓跌 0 → −1
  return -1 + (u - (CYCLE_MONTHS - CYCLE_CRASH)) / CYCLE_CRASH;                // 急涨 −1 → 0
};

/**
 * ── 估值噪声（用户 2026-09-28：「相比上月随机性大一点……不可能一直涨，但是也确保平均」）──
 * 纯锯齿只有一条平顺的坡：缓涨段的「相比上月」连着 57 个月都是一样的斜率，玩家读出来
 * 就是「太规律」。这一层把锯齿**打毛** —— 某个月多涨一点、接着几个月慢下来、再回撤
 * 小跌、然后再起来，也就是用户要的「大涨 → 缓涨 → 回撤 → 小跌 → 又涨」。
 *
 * 形状是**四个整数谐波的正弦叠加**（把整局 480 个月看成波长的整数倍）：
 *   `valNoise(m) = Σ aₖ · sin(2πk·m/480)`
 *
 * ⚠️ **相位必须全部为 0**：`sin(0) = 0` ⇒ `valNoise(0) = valNoise(480) = 0`。
 *    `tools/probes.mjs` 有一条硬断言「周期两端锚点不被污染」（`valAt(0) === valAt(480) === 1`），
 *    给任何一个谐波配上非零相位，`sin(φₖ) ≠ 0`，这条立刻翻红。
 * ⚠️ **整数谐波**是第二条约束：480 是它们的整数个周期 ⇒ 噪声自身也**周期闭合**，
 *    并且整数月的均值和恰好为 0（`Σ sin(2πk·m/480) = 0`），「确保平均」靠的就是这一条。
 * ⚠️ **k 取大值（31 / 53 / 79 / 113）而不是低谐波**：噪声对「相比上月」的贡献是它的
 *    **一阶差分**，而差分的幅度 ∝ k。低谐波（7/11/17/23）的月变化只有 ±0.9%，
 *    被 3~5% 的阶梯月增速整个盖住 —— 加了等于没加。这四个 k 的波长是 15.5 / 9.1 / 6.1 / 4.2 个月，
 *    月变化落在 ±4% 量级，与阶梯增速同一档次，那个数才终于会**上下跳**。
 *    实测（`best` 路径 293 个月）：「相比上月」为负的月份从 6 个（全是周期的骤跌段）变成 12 个。
 * ⚠️ 幅度 `VAL_NOISE_AMP = 0.05`、`Σa = 1.17` ⇒ `valAt` 的带从 ±25% 变成 **约 ±31%**
 *    （最冷 0.69 / 最热 1.31），仍在「温和」档内；月度扰动 σ ≈ 1.5%，
 *    年度尺度上被均掉，所以 `npm run tune` 的阶梯与 `check` 的章节时长不受系统性影响。
 * ⚠️ 只许用这个写法：`Math.random()` 在本项目里是**禁区**（存档必须可复现）。
 */
export const VAL_NOISE_AMP = 0.05;
/** 四个谐波的权重（`k` 与 480 互质，避免几个峰叠在同一个月上、也避免与 120 月周期共相位） */
const NOISE_HARMONICS = [
  { k: 31, a: 0.55 }, { k: 53, a: 0.30 }, { k: 79, a: 0.20 }, { k: 113, a: 0.12 },
];
/**
 * ⚠️ `480` 写**字面量**、不引 `MONTHS_TOTAL`：`content.js` 对外零 `import` 是刻意的
 *    （`format.js` 反过来读本文件的 `ACTS` / `START_MCAP`，引回去就成环）。
 */
const valNoise = m => {
  const t = (m / 480) * Math.PI * 2;
  let v = 0;
  for (const h of NOISE_HARMONICS) v += h.a * Math.sin(h.k * t);
  return v;
};

/** 第 `m` 个月的估值乘数：1 = 平常 ｜ **约 1.31 最热** ｜ **约 0.69 最冷**（含噪声） */
export const valAt = m => 1 + VAL_CYCLE_AMP * cycleAt(m) + VAL_NOISE_AMP * valNoise(m);
/** 第 `m` 个月的成本乘数：1 = 平常 ｜ **0.70 最便宜** ｜ **1.30 寒冬最贵** */
export const winterAt = m => 1 - COST_CYCLE_AMP * cycleAt(m);

