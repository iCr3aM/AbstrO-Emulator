// ─────────────────────────── 支出与净利率（GDD §5.1）───────────────────────────
/**
 * 工资占营收比例：30% → 45%（越往后人越多、越贵）
 * 出租屋阶段三个人**不给自己发工资**（只付外包与服务器），所以第 1 章起点压到 30%。
 */
const SALARY_FRAC = [null, 0.30, 0.33, 0.36, 0.39, 0.42, 0.44, 0.45, 0.45];
/**
 * 规模维护占营收比例：18% → 33%（公司越大，管理 / 协调 / 合规 / 内耗越贵）。
 * 成熟期「重资产」（自建数据中心 / 算力集群）把净利率压到 22% —— 低于微软的 36%，
 * 与算力密集行业的真实资本开支相符。
 */
const SCALE_FRAC = [null, 0.18, 0.22, 0.26, 0.29, 0.31, 0.32, 0.32, 0.33];

const at = (t, stage) => t[Math.max(1, Math.min(8, stage | 0))];
export const salaryFrac = stage => at(SALARY_FRAC, stage);
export const scaleFrac = stage => at(SCALE_FRAC, stage);
/**
 * 净利率 = 1 − 工资 − 规模维护：**52% → 22%**。
 * 现实锚点（成熟科技营业利润率）：Micron 26% / SS&C 38% / Cadence 44.6%；
 * 早期公司其实**是亏的**，游戏里第 1 章给 52%（三个人不领薪的那点家底）。
 * 末章维持 22%（只比旧值 0.20 高一丝）—— 「终局不加快」的主保证是 `CURVE_MID` 的末章时长。
 */
export const marginOf = stage => 1 - salaryFrac(stage) - scaleFrac(stage);

