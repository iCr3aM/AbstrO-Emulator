/**
 * 自动购买的「让路储备」：自动要攒够 `AUTO_BUY_RESERVE` 次购买额才动手。
 * 它不动「一次购买花一份钱」的算术（所以几乎不拖慢整体），唯一作用是
 * **给玩家留出一段买得起的窗口** —— 没有它，钱会在同一个 tick 里被自动买光，
 * 手动按钮永远点不动。K=2 ⇒ 约半个购买周期里按钮是亮的（那是「轮到你了」的信号）。
 *
 * ⚠️ 它只决定「自动什么时候动手」，**不改变稳态购买速率**：买完一手之后账上剩
 *    `(K−1) × cost`，再攒 `1 × cost` 就又到门槛 ⇒ 两次购买之间永远隔着一个 `cost` 的
 *    时间。所以抬高 K 是**免费**的：玩家的窗口变大，而挂机路径的节奏几乎不动
 *    （只多等一次「起手」的 `(K−1) × cost`）。`npm run tune` 因此不需要重排阶梯。
 */
