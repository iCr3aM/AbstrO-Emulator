/**
 * 现金储备比例（用户 2026-09-26）：**账上永远留一笔不能动的钱**。
 * 一家公司不可能把账上全部现金一次性拿去买东西 —— 储备金就是那条底线：
 * 「现金 − 储备金」才是可动用的额度，自动购买与手动点击**都必须绕开它**。
 *
 * ### 基数是**现金**，不是年营收（用户 2026-09-27）
 * 旧版是 `储备 = 年营收 × 0.25`。那等于一道 `≈10 份成本`（`年营收 / cost = 41.02`）的硬墙：
 * 现金没填满这条线之前**一分钱都动不了**，表现就是「现金明明在涨、按钮全是灰的」。
 * 现在改成 `储备 = 现金 × rf` ⇒ 储备永远只是钱包的一个固定份额，**永远有 (1−rf) 能动**，
 * 且「现金少了储备自然跟着少」这件事变成数学恒等式，不需要额外规则。
 *
 * ### 取值 0.80 的理由（用户 2026-09-27 拍板）
 * 自动购买是「钱一够就买」⇒ 现金**永远不会累积**，它是购买周期里的一个锯齿，上沿由
 * `AUTO_BUY_RESERVE` 决定。于是有恒等式（推导见 `economy.js` 顶部）：
 * ```
 * 现金 / 年营收 ∈ [ K/(1−rf) − 1 , K/(1−rf) ] / 41.02      K = 2（融资后）
 * ```
 * 旧值 0.25 ⇒ **4.1% – 6.5%**：比现实里最低的 SS&C（7.4%）还低，「年营收 3.3 万亿、
 * 储备只有几百亿」就是从这里来的（用户 2026-09-27 报的）。
 * 0.80 ⇒ **21.9% – 24.4%**（终局实测 `21.1%`），正落在 Micron 25.7% 与 Microsoft 33.6% 之间 ——
 * 现实里科技公司「现金及等价物 ÷ 年营收」最典型的一档。
 *
 * ⚠️ 它**不改稳态购买速率**（推导见 `economy.js`：`(1−rf)` 在周期长度的分子分母上相消），
 *    是**免费**的旋钮 —— 唯一代价是「开局把锯齿填满」的那一次时延（约 +3 分钟）。
 * ⚠️ 它**会**影响手动可点空间（窗口宽度 `(1−rf)·cost`），所以改它必须重跑 `npm run robust`。
 */
export const RESERVE_FRAC = 0.80;

