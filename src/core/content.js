/**
 * ── 决胜段减速（用户 2026-09-27：「让玩家在登顶之前速度强制变慢」）──
 * `engine.dilate(s)` 给 `dt` 再乘一个因子，`worldBest` 越小越慢。它乘在 `s.speed` **之外**，
 * 所以玩家选 8× 时决胜段实际是 `8 × 0.5 = 4×` —— **玩家关不掉**，这就是「强制」的含义
 * （不这样，倍速一开，最后几分钟一眨眼就过去了，用户要的「慢慢超越」根本没机会出现）。
 *
 * ### 为什么用**名次**做键，而不是「与榜首的差距」
 * 日历与世界都由玩家市值驱动（`calMonthOf` 读 `marketCapBase`、`worldTick` 的
 * `target = gameMonths(s)`）⇒ 把玩家减速 2×，世界也跟着慢 2×、榜首同样慢下来，
 * 差距比 `gap` 基本只是日期的函数 —— 实测减速对它是**几乎无效**的。
 * 名次是「相对位置」的离散读数，不受这个耦合影响。
 *
 * ⚠️ 这两个常数放**这里**（而不是 `engine.js`）是因为 `world.js` 也要用 `DIL_AT`
 *    （`worldTick` 里那条「决胜 · 时间放慢」日志回执的判据）。`engine.js` 从 `world.js`
 *    引 `worldTick`，常数写在 engine 就成了反向依赖；`content.js` 零 import，两边都能引。
 * ⚠️ `DIL_AT` **不能太大**：第 7 章的实测偏差本来就贴着容差（+39.3%），而玩家在
 *    第 7 章末尾就已经进到第 10 名 —— 减速带只要伸进第 7 章（`DIL_AT ≥ 10`），
 *    那一章就会被推过 `CURVE_TOL = 0.4`（实测 1.123h / +40.4%），`check` 直接判红。
 *    取 5 让减速**整段落在第 8 章内**：实测第 7 章 1.114h / +39.3%（与减速前逐位一致），
 *    第 8 章 1.257h / +14%，全程 5.52h —— 逐章与总带宽都留在容差里，`tune` 保持幂等。
 *    对照：`DIL_AT = 10` 时第 7 章被推成 1.123h / +40.4%、第 8 章 1.555h / +41%，两章同时判红。
 */
export const DIL_MIN = 0.5;
