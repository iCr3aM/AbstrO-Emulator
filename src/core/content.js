/**
 * ── 回味期时钟与市值口径（第九批 · 登顶后的市值模拟器）──
 * ===============================================================
 * 登顶之后**日历不再由「市值进度钟」驱动**，改由**真实秒**驱动：
 * 1 真实分钟 = `SAVOR_MONTHS_PER_MIN` 游戏月（= 1 游戏年），封顶 `SAVOR_END_MONTH`（2086-08）。
 * 两条线刻意不同步：**日历是主角（走 20 年）、经营是背景音（`SAVOR_RATE` 只走 1.2 年）**。
 *
 * 玩家市值**不自由生长**，而是锚在**世界榜首（不含玩家，即榜上第二名）**上：
 * ```
 * 玩家市值 = 榜首 + gap(月) + 交接余量
 * gap(月) = (SAVOR_GAP_MID + SAVOR_GAP_AMP × cycleAt(月)) × u
 * u = min(1, age / SAVOR_RAMP_MONTHS)      age = gameMonths − s.topMonth
 * 交接余量 = max(0, 自己 − 榜首) × max(0, 1 − age / SAVOR_HANDOFF_MONTHS)
 * ```
 * 为什么不能自由生长：经营在回味期照跑且**复利**，自己的账面市值 20 真实分钟会从 28 T 涨到
 * **259 T**（实测 ×9.25）—— 远超「只比第二名多一点」的口径；锚在榜首上之后得到 113~123 T，
 * 且 `gap > 0` ⇒ **结构上不可能被超越**。
 *
 * ⚠️ 自己的账面市值**不能掺进市值公式**（实测两次）：线性混合会把自己压到榜首之下（掉名次），
 *    取 `max` 则被复利顶到 161 T。唯一的例外是登顶那一帧的**交接余量** —— 它只是让 HUD
 *    不要凭空跌 7%，并在 2 真实分钟内衰减干净，所以泄漏的长度只有那 2 分钟。
 * `u` 横跨**整个回味期**（`SAVOR_RAMP_MONTHS`）⇒ gap 是一条**缓慢曲线**，
 * 到封顶 2086-08 才走到 10~20 T（= R4 定的「比第二名多 10-20 T」）。
 */
export const SAVOR_MONTHS_PER_MIN = 12;
